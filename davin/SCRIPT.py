def load_and_preprocess_ecg5000(filepath):
    """Return the train, validation and test sets as (points, class) pairs."""
    lines = open(filepath).read().splitlines()
    first = [i for i, line in enumerate(lines) if line.upper().startswith("@DATA")][0] + 1
    table = np.array([line.split(",") for line in lines[first:] if line.strip()], dtype=np.float32)
    x, y = table[:, :-1], table[:, -1].astype(int)

    x_train, x_rest, y_train, y_rest = train_test_split(x, y, test_size=0.30, random_state=42, stratify=y)
    x_val, x_test, y_val, y_test = train_test_split(x_rest, y_rest, test_size=0.50, random_state=42, stratify=y_rest)

    scaler = StandardScaler().fit(x_train)
    return {"train": (scaler.transform(x_train), y_train),
            "val": (scaler.transform(x_val), y_val),
            "test": (scaler.transform(x_test), y_test)}


# SECTION 2: Baselines

def run_baselines(data):
    """Return the test accuracy of both baselines."""
    majority = max(np.mean(data["test"][1] == c) for c in np.unique(data["test"][1]))
    linear = LogisticRegression(max_iter=2000).fit(*data["train"])
    return {"majority class": majority, "logistic regression": linear.score(*data["test"])}


# SECTION 3: Base Neural Network Definition (Feedforward MLP)

ACTIVATION = "relu"                  # hidden layers: max(0, x)
INITIALISER = "he_normal"            # starting weights suited to ReLU
L2_PENALTY = 1e-4                    # weight decay added to the loss
OUTPUT_ACTIVATION = "softmax"        # one probability per class
LOSS = "sparse_categorical_crossentropy"
LEARNING_RATE = 0.001                # Adam
BATCH_SIZE = 32                      # heartbeats per weight update
MAX_EPOCHS = 100                     # limit on passes over the training data
PATIENCE = 5                         # epochs without a better validation loss before stopping
SEARCH_GRID = [(hidden, dropout) for hidden in [(32,), (64, 32), (128, 64)] for dropout in (0.0, 0.3)]


def build_base_mlp(input_dim, num_classes, hidden, dropout):
    """Build input, then Dense + ReLU + Dropout per hidden layer, then softmax output."""
    stack = [layers.Input(shape=(input_dim,), name="ECG_points")]
    for i, units in enumerate(hidden, start=1):
        stack.append(layers.Dense(units, activation=ACTIVATION, kernel_initializer=INITIALISER,
                                  kernel_regularizer=regularizers.l2(L2_PENALTY), name=f"Dense_{i}_{units}_ReLU"))
        stack.append(layers.Dropout(dropout, name=f"Dropout_{i}"))
    stack.append(layers.Dense(num_classes, activation=OUTPUT_ACTIVATION, name="Softmax_classes"))
    model = models.Sequential(stack, name="Base_Feedforward_MLP")
    model.compile(optimizer=tf.keras.optimizers.Adam(learning_rate=LEARNING_RATE),
                  loss=LOSS, metrics=["accuracy"])
    return model


# SECTION 4: Training with Early Stopping

def train_model(hidden, dropout, data, seed):
    """Return the trained model, its history and the training seconds."""
    tf.keras.utils.set_random_seed(seed)
    x_train, y_train = data["train"]
    model = build_base_mlp(x_train.shape[1], len(np.unique(y_train)), hidden, dropout)
    stop = callbacks.EarlyStopping(monitor="val_loss", patience=PATIENCE, restore_best_weights=True)

    start = time.perf_counter()
    history = model.fit(x_train, y_train, validation_data=data["val"], epochs=MAX_EPOCHS,
                        batch_size=BATCH_SIZE, callbacks=[stop], verbose=0)
    return model, history.history, time.perf_counter() - start


# SECTION 5: Search over Architecture and Dropout

def run_search(data):
    """Return the settings sorted from lowest to highest validation loss."""
    rows = []
    for hidden, dropout in SEARCH_GRID:
        model, hist, seconds = train_model(hidden, dropout, data, seed=0)
        val_loss, val_acc = model.evaluate(*data["val"], verbose=0)
        rows.append((val_loss, hidden, dropout, val_acc, len(hist["loss"]), seconds))
    return sorted(rows, key=lambda row: row[0])


# SECTION 6: Fit Check, Evaluation and Reporting

SEEDS = (0, 1, 2)
GAP_LIMIT = 0.01        # train accuracy minus validation accuracy above this means over-fitting


def diagnose_fit(model, hist, data):
    """Under-fitting: train accuracy not above the majority-class rate. Over-fitting: gap above GAP_LIMIT."""
    train_acc = model.evaluate(*data["train"], verbose=0)[1]
    val_acc = model.evaluate(*data["val"], verbose=0)[1]
    majority = np.bincount(data["train"][1]).max() / len(data["train"][1])
    gap = 100 * (train_acc - val_acc)
    if train_acc <= majority:
        status = "UNDERFITTING (not better than always guessing the majority class)"
    elif train_acc - val_acc > GAP_LIMIT:
        status = f"OVERFITTING (train-validation gap {gap:.2f} points)"
    else:
        status = f"NO SIGN OF EITHER (train-validation gap {gap:.2f} points)"
    return train_acc, val_acc, int(np.argmin(hist["val_loss"])) + 1, status


def report_specification(hidden, dropout, data):
    banner("1. BASE MODEL SPECIFICATION")
    model = build_base_mlp(data["train"][0].shape[1], len(np.unique(data["train"][1])), hidden, dropout)
    print("Base architecture : Standard feedforward multilayer perceptron (MLP)")
    print(f"Input             : {data['train'][0].shape[1]} ECG points per heartbeat, standardised on train data")
    print(f"Hidden layers     : {' -> '.join(str(u) for u in hidden)} neurons, {ACTIVATION}, {INITIALISER} initial weights")
    print(f"Regularisation    : L2 {L2_PENALTY}, dropout {dropout}, early stopping (patience {PATIENCE})")
    print(f"Output            : {OUTPUT_ACTIVATION} over {len(np.unique(data['train'][1]))} classes")
    print(f"Training          : Adam (learning rate {LEARNING_RATE}), {LOSS}, batch {BATCH_SIZE}, up to {MAX_EPOCHS} epochs")
    model.summary()


def report_baselines_and_search(baselines, rows, data):
    banner("2. BASELINES AND SEARCH")
    print(f"Split: {len(data['train'][1])} train, {len(data['val'][1])} validation, {len(data['test'][1])} test heartbeats")
    for name, accuracy in baselines.items():
        print(f"Baseline, test accuracy : {name:<20s} {accuracy:.4f}")
    print(f"\n{'hidden layers':>14} {'dropout':>8} {'epochs':>7} {'seconds':>8} {'val acc':>8} {'val loss':>9}")
    for loss, hidden, dropout, acc, epochs, seconds in rows:
        print(f"{str(list(hidden)):>14} {dropout:>8} {epochs:>7} {seconds:>8.1f} {acc:>8.4f} {loss:>9.4f}")


def report_final(hidden, dropout, data):
    """Train three seeds; the first seed is kept for the runtime and per-class report."""
    banner("3. FIT QUALITY DIAGNOSIS AND FINAL TEST (UNSEEN DATA)")
    print(f"{'seed':>4} {'best epoch':>11} {'train acc':>10} {'val acc':>8} {'test acc':>9} {'test loss':>10}  diagnosis")
    test_accs, detail = [], None
    for seed in SEEDS:
        model, hist, seconds = train_model(hidden, dropout, data, seed)
        train_acc, val_acc, best, status = diagnose_fit(model, hist, data)
        test_loss, test_acc = model.evaluate(*data["test"], verbose=0)
        test_accs.append(test_acc)
        print(f"{seed:>4} {best:>11} {train_acc:>10.4f} {val_acc:>8.4f} {test_acc:>9.4f} {test_loss:>10.4f}  {status}")
        if detail is None:
            detail = (model, hist, seconds)
    print(f"\nTest accuracy over {len(SEEDS)} seeds: mean {np.mean(test_accs):.4f}, "
          f"range {min(test_accs):.4f} to {max(test_accs):.4f}")
    return detail


def report_runtime_and_per_class(model, hist, seconds, data):
    x_test, y_test = data["test"]
    model.predict(x_test[:32], verbose=0)                       # warm-up call, not timed
    start = time.perf_counter()
    pred = np.argmax(model.predict(x_test, verbose=0), axis=1)
    infer = time.perf_counter() - start
    epochs = len(hist["loss"])

    banner("4. RUNTIME AND PER-CLASS REPORT (SEED 0)")
    print(f"Training {seconds:.2f} s for {epochs} epochs; inference {infer / len(x_test) * 1000:.4f} ms per heartbeat")
    print(f"Classification error: {np.sum(pred != y_test)} of {len(y_test)} wrong")
    report = classification_report(y_test, pred, zero_division=0, output_dict=True)
    line = "{:<10} {:>10} {:>8} {:>9} {:>8}"                    # one column grid for every row
    print("\n" + line.format("class", "precision", "recall", "f1-score", "support"))
    for c in np.unique(y_test):
        r = report[str(c)]
        print(line.format(c, f"{r['precision']:.2f}", f"{r['recall']:.2f}", f"{r['f1-score']:.2f}", f"{r['support']:.0f}"))
    print(line.format("accuracy", "-", "-", f"{report['accuracy']:.2f}", len(y_test)))   # one score over all beats


# MAIN

if __name__ == "__main__":
    data = load_and_preprocess_ecg5000(locate_data_file())
    baselines = run_baselines(data)
    rows = run_search(data)
    hidden, dropout = rows[0][1], rows[0][2]

    report_specification(hidden, dropout, data)
    report_baselines_and_search(baselines, rows, data)
    model, hist, seconds = report_final(hidden, dropout, data)
    report_runtime_and_per_class(model, hist, seconds, data)